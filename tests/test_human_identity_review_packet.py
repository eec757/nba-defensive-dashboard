"""Safety tests for human identity review packet generation."""
import importlib.util
from pathlib import Path
import sys
import unittest

ROOT=Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location("packet",ROOT/"scripts/build_human_identity_review_packet.py")
packet=importlib.util.module_from_spec(spec)
spec.loader.exec_module(packet)

class ReviewPacketTests(unittest.TestCase):
    def test_unapproved_candidate_never_receives_reviewer_or_approval(self):
        candidates=[{
            "nba_player_id":"1643813","bref_id":"unknown","position":"SF",
            "verified":"false","reviewed_by":"autogenerated",
            "reviewed_on":"2026-10-24",
            "nba_profile_url":"https://www.nba.com/player/1643813",
            "verification_source":"https://www.wikidata.org/wiki/Q123",
            "position_source":"https://example.com/roster"
        }]
        evidence=[{"nba_player_id":"1643813","bref_id":"unknown","status":"unsupported"}]
        rows=packet.build_packet(candidates,evidence)
        self.assertEqual(len(rows),1)
        self.assertEqual(rows[0]["review_decision"],"pending_human_review")
        self.assertEqual(rows[0]["current_live_verified"],"no")
        self.assertEqual(rows[0]["reviewer"],"")
        self.assertEqual(rows[0]["review_date"],"")
        self.assertEqual(rows[0]["season_position_supported"],"no")

    def test_existing_approval_is_not_new_review(self):
        rows=packet.build_packet([{"nba_player_id":"1","bref_id":"a","verified":"true"}],[])
        self.assertEqual(rows[0]["review_decision"],"existing_approval")
        self.assertEqual(rows[0]["reviewer"],"")
        self.assertEqual(rows[0]["review_date"],"")

if __name__=="__main__":
    unittest.main()
